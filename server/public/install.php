</style></head><body><main>
<h1>SkpShare installer</h1>
<?php if ($installed && !$done): ?>
  <div class="box">Already installed. <a href="./">Open the app</a>. For safety, delete <code>install.php</code> from your server.</div>
<?php elseif ($done): ?>
  <div class="box"><b class="ok">Installed.</b> Upload chunk size was set to <?= $h(round($chunk / 1048576, 2)) ?> MB to fit your host limits.<br>
  <b>Now delete <code>install.php</code></b> from the server, then <a href="./login">log in</a>.</div>
<?php else: ?>
  <div class="box"><b>Requirements</b><br>
  <?php foreach ($checks as $k => $ok): ?><span class="<?= $ok ? 'ok' : 'bad' ?>"><?= $ok ? '✔' : '✘' ?></span> <?= $h($k) ?><br><?php endforeach; ?>
  <small>Host limits: <?php foreach ($limits as $k => $v) echo $h("$k=$v  "); ?> → chunk size <?= $h(round($chunk / 1048576, 2)) ?> MB</small></div>
  <?php foreach ($errors as $e): ?><div class="box err"><?= $h($e) ?></div><?php endforeach; ?>
  <form method="post">
    <fieldset><legend><b>Database</b> (create an empty MySQL database + user in your hosting panel first)</legend>
    <label>Driver</label><select name="driver"><option value="mysql">MySQL / MariaDB</option><option value="sqlite">SQLite (no server, small teams)</option></select>
    <div class="row"><div><label>Host</label><input name="db_host" value="<?= $h($_POST['db_host'] ?? 'localhost') ?>"></div>
    <div style="max-width:110px"><label>Port</label><input name="db_port" value="<?= $h($_POST['db_port'] ?? '3306') ?>"></div></div>
    <label>Database name</label><input name="db_name" value="<?= $h($_POST['db_name'] ?? '') ?>">
    <label>Database user</label><input name="db_user" value="<?= $h($_POST['db_user'] ?? '') ?>">
    <label>Database password</label><input name="db_pass" type="password"></fieldset>
    <fieldset><legend style="margin-top:20px"><b>First admin account</b></legend>
    <label>Name</label><input name="admin_name" value="<?= $h($_POST['admin_name'] ?? 'Admin') ?>">
    <label>Email</label><input name="admin_email" type="email" required value="<?= $h($_POST['admin_email'] ?? '') ?>">
    <label>Password (min 8)</label><input name="admin_password" type="password" required minlength="8"></fieldset>
    <label>Storage quota for the dashboard gauge (GB, optional)</label><input name="quota_gb" value="0">
    <button>Install</button>
  </form>
<?php endif; ?>
</main></body></html>
