// Renders the dialog with the mock bridge and saves screenshots: node dev/preview.js <outdir>
const { chromium } = require('playwright');
const path = require('path');
const out = process.argv[2] || '.';
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1180, height: 760 }, deviceScaleFactor: 1 });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  await page.addInitScript({ path: path.join(__dirname, 'mock_bridge.js') });
  await page.goto('file://' + path.join(__dirname, '..', 'src', 'banian_browser', 'ui', 'index.html'));
  await page.waitForTimeout(900);
  const shots = async (name) => page.screenshot({ path: path.join(out, name + '.png') });
  await shots('01_models');
  await page.click('.node[data-p="D:/Library/Objects/Furniture"] .nm');
  await page.waitForTimeout(400);
  await shots('02_folder');
  await page.click('.card', { button: 'right' });
  await page.waitForTimeout(200);
  await shots('03_context');
  await page.keyboard.press('Escape'); await page.mouse.click(600, 20);
  await page.click('#rail button[data-v="materials"]');
  await page.waitForTimeout(500);
  await shots('04_materials');
  await page.click('#rail button[data-v="tools"]');
  await page.waitForTimeout(300);
  await shots('05_tools');
  // live material editor: opacity slider applies without a button and keeps the inputs
  await page.$eval('#pm-alpha', (el) => { el.value = 40; el.dispatchEvent(new Event('input', { bubbles: true })); });
  await page.waitForTimeout(400);
  const live = await page.evaluate(() => ({ props: window.__props, still: !!document.getElementById('pm-alpha') && document.getElementById('pm-alpha').value }));
  console.log('live edit:', JSON.stringify(live));
  await page.click('#rail button[data-v="models"]');
  await page.waitForTimeout(300);
  await page.click('[data-act="toggle-info"]');
  await page.waitForTimeout(300);
  await page.click('#pins [data-pin="D:/Library/Objects/Plants"]');
  await page.waitForTimeout(300);
  await shots('06_pins_info');
  await page.click('[data-act="toggle-info"]');
  await page.click('#rail button[data-v="tools"]');
  await page.waitForTimeout(200);
  await page.click('#rail button[data-v="settings"]');
  await page.waitForTimeout(300);
  await shots('07_settings');
  await page.click('[data-set="language"][data-v="en"]');
  await page.waitForTimeout(300);
  await page.click('[data-set="theme"][data-v="dark"]');
  await page.waitForTimeout(300);
  await page.click('#rail button[data-v="models"]');
  await page.waitForTimeout(500);
  await page.fill('#q', 'chair');
  await page.waitForTimeout(400);
  await shots('08_en_dark_search');
  await page.click('#rail button[data-v="inmodel"]');
  await page.waitForTimeout(400);
  await shots('09_inmodel');
  await page.setViewportSize({ width: 600, height: 700 });
  await page.click('#rail button[data-v="materials"]');
  await page.waitForTimeout(400);
  await shots('10_narrow');
  console.log('errors:', JSON.stringify(errors));
  await browser.close();
})();
