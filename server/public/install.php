<?php
declare(strict_types=1);
/**
 * One-time web installer: checks requirements, writes config.php, creates tables and the first admin.
 * It refuses to run once config.php exists. Delete this file after installing.
 */
$root = is_file(__DIR__ . '/../src/bootstrap.php') ? dirname(__DIR__) : __DIR__ . '/_app';
require $root . '/src/bootstrap.php';

use App\Core\Db;

$h = fn($s) => htmlspecialchars((string)$s, ENT_QUOTES);
$installed = is_file($root . '/config.php');
$errors = [];
$done = false;

$checks = [
    'PHP 8.1 or newer' => version_compare(PHP_VERSION, '8.1.0', '>='),
    'PDO MySQL extension' => extension_loaded('pdo_mysql'),
    'zlib extension (SKP compression)' => extension_loaded('zlib'),
    'mbstring extension' => extension_loaded('mbstring'),
    'Application folder writable (config.php)' => is_writable($root),
    'storage/ folder writable' => is_dir($root . '/storage') ? is_writable($root . '/storage') : is_writable($root),
];
$limits = ['upload_max_filesize' => ini_get('upload_max_filesize'), 'post_max_size' => ini_get('post_max_size'),
    'memory_limit' => ini_get('memory_limit'), 'max_execution_time' => ini_get('max_execution_time')];
$toBytes = function (string $v): int {
    $n = (int)$v;
    return match (strtolower(substr(trim($v), -1))) { 'g' => $n << 30, 'm' => $n << 20, 'k' => $n << 10, default => $n };
};
$maxPost = min($toBytes((string)$limits['upload_max_filesize']) ?: PHP_INT_MAX, $toBytes((string)$limits['post_max_size']) ?: PHP_INT_MAX);
$chunk = 4 << 20;
while ($chunk > (256 << 10) && $chunk + (64 << 10) > $maxPost) $chunk >>= 1;

$script = $_SERVER['SCRIPT_NAME'] ?? '/install.php';
$basePath = rtrim(str_replace('\\', '/', dirname($script)), '/');

if (!$installed && ($_SERVER['REQUEST_METHOD'] ?? '') === 'POST') {
    $in = fn($k, $d = '') => trim((string)($_POST[$k] ?? $d));
    $driver = $in('driver', 'mysql') === 'sqlite' ? 'sqlite' : 'mysql';
    $db = $driver === 'sqlite'
        ? ['driver' => 'sqlite', 'path' => $root . '/storage/skpshare.sqlite']
        : ['driver' => 'mysql', 'host' => $in('db_host', 'localhost'), 'port' => (int)$in('db_port', '3306'),
            'name' => $in('db_name'), 'user' => $in('db_user'), 'pass' => (string)($_POST['db_pass'] ?? '')];
    $email = strtolower($in('admin_email'));
    $pass = (string)($_POST['admin_password'] ?? '');
    if (!filter_var($email, FILTER_VALIDATE_EMAIL)) $errors[] = 'Enter a valid admin email.';
    if (strlen($pass) < 8) $errors[] = 'Admin password must be at least 8 characters.';
    if (!$errors) {
        try {
            if (!is_dir($root . '/storage')) mkdir($root . '/storage', 0775, true);
            Db::connect($db);
            Db::migrate($root . '/migrations/schema.sql');
            if (!Db::val('SELECT id FROM users WHERE email = ?', [$email])) {
                Db::insert('users', ['email' => $email, 'name' => $in('admin_name') ?: 'Admin',
                    'password_hash' => password_hash($pass, PASSWORD_DEFAULT), 'role' => 'admin', 'active' => 1,
                    'created_at' => Db::now()]);
            }
            $config = [
                'db' => $db,
                'secret' => bin2hex(random_bytes(32)),
                'base_path' => $basePath,
                'storage_path' => $root . '/storage',
                'chunk_size' => $chunk,
                'max_file_size' => 3 * 1024 ** 3,
                'storage_quota' => (int)((float)$in('quota_gb', '0') * 1024 ** 3),
                'debug' => false,
            ];
            $php = "<?php\n// Generated by install.php on " . gmdate('c') . "\nreturn " . var_export($config, true) . ";\n";
            if (file_put_contents($root . '/config.php', $php) === false) throw new RuntimeException('Cannot write config.php');
            @chmod($root . '/config.php', 0640);
            $done = true;
        } catch (Throwable $e) {
            $errors[] = 'Installation failed: ' . $e->getMessage();
        }
    }
}
